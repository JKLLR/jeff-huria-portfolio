// Writes docs/MOCK_DATA.md: every placeholder in src/_data/mock.json, so
// nothing invented survives to launch unnoticed. Runs on every build.
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const mock = JSON.parse(fs.readFileSync(path.join(root, 'src/_data/mock.json'), 'utf8'));
const projects = JSON.parse(fs.readFileSync(path.join(root, 'src/_data/projects.json'), 'utf8'));
const isEmpty = (v) => v == null || (Array.isArray(v) && v.length === 0) || v === '';

const lines = [];
const flatten = (value, trail) => {
    if (Array.isArray(value) || (value && typeof value === 'object')) {
        Object.entries(value).forEach(([k, v]) => flatten(v, trail.concat(Array.isArray(value) ? `[${k}]` : k)));
    } else {
        lines.push(`| \`${trail.join('.').replace(/\.\[/g, '[')}\` | ${String(value).replace(/\|/g, '\|')} |`);
    }
};

const out = [
    '# Mock data register',
    '',
    'Generated by `scripts/mock-report.js` on every build — do not edit by hand.',
    '',
    'Everything below is **placeholder content** used to design the site. It is highlighted on the page',
    '(toggle with the MOCK pill, bottom left, or the `M` key). Replace each value with the real figure, or',
    'delete it, in `src/_data/mock.json`. Real data in `projects.json` always takes precedence: a mock project',
    'field is only shown while the real field is empty.',
    ''
];

for (const [section, value] of Object.entries(mock)) {
    if (section.startsWith('_') || section === 'projects') continue;
    lines.length = 0;
    flatten(value, [section]);
    out.push(`## ${section}`, '', '| Key | Placeholder |', '|---|---|', ...lines, '');
}

out.push('## projects', '');
for (const [id, fields] of Object.entries(mock.projects || {})) {
    const real = projects.find((p) => p.id === id) || {};
    const shown = Object.keys(fields).filter((f) => isEmpty(real[f]));
    const hidden = Object.keys(fields).filter((f) => !isEmpty(real[f]));
    out.push(`### ${id}`, '');
    out.push(`Shown (real field empty): ${shown.map((f) => `\`${f}\``).join(', ') || '—'}`);
    if (hidden.length) out.push(`Ignored (real data exists): ${hidden.map((f) => `\`${f}\``).join(', ')}`);
    out.push('');
    lines.length = 0;
    shown.forEach((f) => flatten(fields[f], [f]));
    out.push('| Key | Placeholder |', '|---|---|', ...lines, '');
}

fs.writeFileSync(path.join(root, 'docs/MOCK_DATA.md'), out.join('\n'));
console.log(`mock-report: ${Object.keys(mock.projects || {}).length} projects, register written to docs/MOCK_DATA.md`);
